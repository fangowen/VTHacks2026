let current = "en";
const listeners = new Set();

export function getLang() { return current; }
export function setLang(lang) {
  if (!S[lang] || lang === current) return;
  current = lang;
  document.documentElement.lang = LANGS[lang].bcp47;
  for (const f of listeners) f(lang);
}
export function onLangChange(f) { listeners.add(f); return () => listeners.delete(f); }

// t("a_navStart", { place: "Newman Library", min: 4 }) — falls back to English for missing keys
export function t(key, vars = {}, lang = current) {
  const s = S[lang]?.[key] ?? S.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

// Pick the current language out of a { en, es, ... } object (used by the campus data)
export function pickLang(obj, lang = current) {
  if (obj == null || typeof obj !== "object") return obj;
  return obj[lang] ?? obj.en;
}

export function fmtTime(mins, lang = current) {
  const d = new Date(2026, 0, 5, Math.floor(mins / 60), Math.round(mins % 60));
  return new Intl.DateTimeFormat(LANGS[lang].bcp47, { hour: "numeric", minute: "2-digit" }).format(d);
}
export function fmtDistance(m, lang = current) {
  return m < 1000 ? t("meters", { n: Math.round(m / 10) * 10 }, lang) : t("km", { n: (m / 1000).toFixed(1) }, lang);
}
export function fmtDuration(mins, lang = current) {
  mins = Math.round(mins);
  if (mins < 60) return `${mins} ${t("min", {}, lang)}`;
  const h = Math.floor(mins / 60), m = mins % 60;
  return m ? `${h} ${t("hr", {}, lang)} ${m} ${t("min", {}, lang)}` : `${h} ${t("hr", {}, lang)}`;
}
export const dayName = (d, lang = current) => t(`day${d}`, {}, lang);
export function joinList(items, lang = current) {
  const sep = { zh: "、", ko: ", ", hi: ", " }[lang] ?? ", ";
  return items.join(sep);
}

